"""The renderers of the schema generator.

The generator writes the schema bundle into a source file of an SDK, so that
the SDK carries the contract and needs no file of the repository at run time.
The rendered file holds the documents as a literal, so the SDK reads no file
and parses no JSON at run time.
"""

from __future__ import annotations

import json
import math
from typing import Any, Mapping

from typcast_schemagen.errors import SchemagenError

__all__ = ["render_python", "render_typescript"]

_DESCRIPTION = """The JSON Schema contract of the document IR.

The file is generated by `//tools/schemagen` from the schema bundle that
`//specs/schemas:schema_bundle` produces. Do not edit it."""


def render_python(documents: Mapping[str, Any]) -> str:
    """Returns the Python source that holds the schema documents."""
    lines = [
        f'"""{_DESCRIPTION}',
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        '__all__ = ["SCHEMAS"]',
        "",
        "SCHEMAS: dict[str, dict[str, Any]] = {",
    ]
    for path in sorted(documents):
        lines.append(f"    {path!r}: {_python_value(documents[path], 1)},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_typescript(documents: Mapping[str, Any]) -> str:
    """Returns the TypeScript source that holds the schema documents."""
    ordered = {path: documents[path] for path in sorted(documents)}
    literal = json.dumps(ordered, indent=2, ensure_ascii=False)
    # The literal holds the braces of the object. The source holds them too,
    # so the braces of the literal are dropped.
    inner = literal.strip()[1:-1].strip("\n")
    body = "\n".join(f"  {line}" for line in inner.splitlines())
    comment = "\n".join(
        f" * {line}" if line else " *" for line in _DESCRIPTION.splitlines()
    )
    return (
        "/**\n"
        f"{comment}\n"
        " *\n"
        " * The documents are a literal, so the SDK reads no file and parses no\n"
        " * JSON at run time.\n"
        " */\n"
        "\n"
        "export const SCHEMAS: Readonly<\n"
        "  Record<string, Readonly<Record<string, unknown>>>\n"
        "> = {\n"
        f"{body}\n"
        "};\n"
    )


def _python_value(value: Any, depth: int) -> str:
    """Returns the Python literal of a JSON value."""
    indent = "    " * depth
    inner = "    " * (depth + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = ["{"]
        for key, item in value.items():
            lines.append(f"{inner}{key!r}: {_python_value(item, depth + 1)},")
        lines.append(indent + "}")
        return "\n".join(lines)
    if isinstance(value, list):
        if not value:
            return "[]"
        lines = ["["]
        for item in value:
            lines.append(f"{inner}{_python_value(item, depth + 1)},")
        lines.append(indent + "]")
        return "\n".join(lines)
    if isinstance(value, str):
        return repr(value)
    if value is True:
        return "True"
    if value is False:
        return "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return repr(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise SchemagenError("a schema holds a number that is not finite")
        return repr(value)
    raise SchemagenError(f"a schema holds a value of the type {type(value).__name__}")
