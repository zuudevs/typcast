/**
 * The Typst emitter of the document IR.
 *
 * The emitter turns a validated document into deterministic Typst source. It is
 * a pure function of the document: it reads no file, invokes no compiler, and
 * writes no file. The Python SDK applies the same rules in
 * `src/typcast/emitter/emitter.py`, so that both SDKs produce the same bytes
 * for the same document.
 *
 * The output contract is the one of `docs/specifications/emitter.md`, and the
 * escaping rules are the ones of `docs/specifications/nodes.md`.
 */

import { requireApiOptions } from "../api.js";
import {
  CODE_EMIT_INVARIANT,
  CODE_EMIT_UNKNOWN_TYPE,
  CODE_EMIT_UNSAFE_VALUE,
  throwEmit,
} from "../diagnostics.js";
import type { Block } from "../models/blocks.js";
import {
  Heading,
  Image,
  ListBlock,
  PageBreak,
  Paragraph,
  RawBlock,
  Table,
} from "../models/blocks.js";
import type { Document } from "../models/document.js";
import type { Module } from "../models/module.js";
import type { Length } from "../models/page.js";
import type { Span } from "../models/spans.js";
import {
  Bold,
  Italic,
  LineBreak,
  Link,
  Monospace,
  RawSpan,
  Text,
} from "../models/spans.js";
import { resolveOptions } from "../validations/config.js";
import type { TypcastOptions } from "../validations/config.js";
import { SEVERITY_ERROR, ValidationError } from "../diagnostics.js";
import type { Diagnostic } from "../diagnostics.js";

/**
 * The header of every generated file.
 *
 * It names no version, so that a release does not change the golden files.
 */
export const EMITTER_HEADER = "// Generated by Typcast. Do not edit.";

/**
 * The characters that a text span escapes in the markup of Typst.
 *
 * The rule is the one of the escaping table of
 * `docs/specifications/nodes.md`. The Python SDK applies the same rule.
 */
const TEXT_ESCAPES: Readonly<Record<string, string>> = {
  "\\": "\\\\",
  "#": "\\#",
  "*": "\\*",
  "_": "\\_",
  "`": "\\`",
  $: "\\$",
  "[": "\\[",
  "]": "\\]",
  "<": "\\<",
  ">": "\\>",
  "@": "\\@",
};

/**
 * The characters that a string literal escapes.
 *
 * A string literal of Typst holds no markup, so only the backslash and the
 * quote need an escape. The Python SDK applies the same rule.
 */
const STRING_ESCAPES: Readonly<Record<string, string>> = {
  "\\": "\\\\",
  '"': '\\"',
};

/**
 * The list markers of the markup of Typst.
 *
 * A text that starts a line and starts with a marker would open a list, so
 * the marker is escaped.
 */
const LIST_MARKERS = ["-", "+"];

/**
 * The pattern of a date of the metadata.
 *
 * The model checks the pattern already, so a value that does not match it
 * means that an invariant of the model broke.
 */
const DATE_PATTERN = /^([0-9]{4})-([0-9]{2})-([0-9]{2})$/;

/** The sides of a margin, in the order of the emission. */
const MARGIN_SIDES = ["top", "right", "bottom", "left"] as const;

/**
 * Returns the text of a span in the markup of Typst.
 *
 * Every character of the escaping table of the node catalog is escaped. A
 * text that starts a line and starts with a list marker is escaped as well,
 * because Typst would read the marker as the start of a list. The Python SDK
 * applies the same rule.
 */
export function escapeText(value: string, lineStart = false): string {
  let text = "";
  for (const character of value) {
    text += TEXT_ESCAPES[character] ?? character;
  }
  if (lineStart && LIST_MARKERS.includes(value.slice(0, 1))) {
    if (value.length === 1 || value[1] === " ") {
      text = `\\${text}`;
    }
  }
  return text;
}

/**
 * Returns the value in a string literal of Typst.
 *
 * A string literal holds no markup, so only the backslash and the quote are
 * escaped. The Python SDK applies the same rule.
 */
export function escapeString(value: string): string {
  let text = "";
  for (const character of value) {
    text += STRING_ESCAPES[character] ?? character;
  }
  return text;
}

/**
 * Returns the path of an asset with the separator of Typst.
 *
 * The path of the IR uses the separator `/`, and the emitter emits it with
 * that separator. A path that holds a backslash is normalized, so that the
 * same asset is named on every platform.
 */
export function normalizePath(value: string): string {
  return value.replaceAll("\\", "/");
}

/**
 * Returns the length in the form of Typst.
 *
 * The number is written in the canonical form of the IR, so that both SDKs
 * write the same text, and the unit follows the number without a space.
 */
export function formatLength(length: Length): string {
  return `${length.value}${length.unit}`;
}

/**
 * Returns the Typst source of a document.
 *
 * The function validates the document before it emits it, so that a document
 * that breaks a semantic rule is reported with the diagnostic of the rule
 * instead of being emitted. The options hold the limits of the validation
 * run, and they are never stored in the document.
 */
export function emitTypst(
  document: Document,
  options?: TypcastOptions,
): string {
  const settings = resolveOptions(
    options === undefined
      ? undefined
      : requireApiOptions<TypcastOptions>(
          options,
          "/to_typst",
          "a TypcastOptions object",
        ),
  );
  const diagnostics = document.validate(settings);
  const errors = diagnostics.filter(
    (diagnostic) => diagnostic.severity === SEVERITY_ERROR,
  );
  const [first, ...rest] = errors;
  if (first !== undefined) {
    const all: readonly Diagnostic[] = [first, ...rest];
    throw new ValidationError(first.message, all);
  }
  return new Emitter(document).emit();
}

/**
 * Turns a document into Typst source.
 *
 * The class holds the state of one emission. Every method returns a part of
 * the output, and `emit()` joins the parts with the blank lines of the output
 * contract.
 */
class Emitter {
  private readonly document: Document;

  constructor(document: Document) {
    this.document = document;
  }

  /** Returns the Typst source of the document. */
  emit(): string {
    const sections: string[] = [EMITTER_HEADER];
    const imports = this.imports();
    if (imports !== "") {
      sections.push(imports);
    }
    sections.push(this.pageSetup());
    sections.push(this.metadata());
    this.document.contents.forEach((block, index) => {
      sections.push(this.block(block, `/contents/${index}`));
    });
    // The output ends with exactly one newline.
    return `${sections.join("\n\n")}\n`;
  }

  // -------------------------------------------------------------------------
  // The sections of the output
  // -------------------------------------------------------------------------

  /** Returns the import section of the output. */
  private imports(): string {
    const lines: string[] = [];
    this.document.modules.forEach((module, index) => {
      lines.push(this.moduleImport(module, `/modules/${index}`));
    });
    return lines.join("\n");
  }

  /** Returns the import of one module. */
  private moduleImport(module: Module, path: string): string {
    const source = escapeString(normalizePath(module.path));
    if (module.alias !== null) {
      return `#import "${source}" as ${module.alias}`;
    }
    const items = module.items ?? [];
    return `#import "${source}": ${items.join(", ")}`;
  }

  /** Returns the page setup of the output. */
  private pageSetup(): string {
    const page = this.document.page;
    const margin = page.margin;
    const sides = MARGIN_SIDES.map(
      (side) => `${side}: ${formatLength(margin[side])}`,
    ).join(", ");
    const flipped = page.orientation === "landscape" ? "true" : "false";
    return [
      "#set page(",
      `  paper: "${escapeString(page.paper)}",`,
      `  flipped: ${flipped},`,
      `  margin: (${sides}),`,
      ")",
    ].join("\n");
  }

  /** Returns the document metadata of the output. */
  private metadata(): string {
    const metadata = this.document.metadata;
    const lines: string[] = [
      "#set document(",
      `  title: "${escapeString(metadata.title)}",`,
    ];
    if (metadata.author !== null) {
      lines.push(`  author: "${escapeString(metadata.author)}",`);
    }
    if (metadata.date !== null) {
      lines.push(`  date: ${this.date(metadata.date, "/metadata/date")},`);
    }
    lines.push(")");
    return lines.join("\n");
  }

  /** Returns the date of the metadata in the form of Typst. */
  private date(value: string, path: string): string {
    const match = DATE_PATTERN.exec(value);
    if (match === null) {
      // The model checks the date, so a value that does not match the pattern
      // means that an invariant of the model broke.
      throwEmit(
        CODE_EMIT_INVARIANT,
        `'${path}' is not a date of the form YYYY-MM-DD.`,
        path,
        { value },
      );
    }
    const [, year, month, day] = match;
    return `datetime(year: ${year}, month: ${month}, day: ${day})`;
  }

  // -------------------------------------------------------------------------
  // The blocks of the output
  // -------------------------------------------------------------------------

  /** Returns the source of one block. */
  private block(block: Block, path: string): string {
    const kind = block.type;
    if (kind === "heading" && block instanceof Heading) {
      return `${"=".repeat(block.level)} ${this.inline(
        block.content,
        `${path}/content`,
      )}`;
    }
    if (kind === "paragraph" && block instanceof Paragraph) {
      return this.inline(block.content, `${path}/content`, true);
    }
    if (kind === "list" && block instanceof ListBlock) {
      return this.list(block, path);
    }
    if (kind === "table" && block instanceof Table) {
      return this.table(block, path);
    }
    if (kind === "image" && block instanceof Image) {
      return this.image(block, path);
    }
    if (kind === "pageBreak" && block instanceof PageBreak) {
      return "#pagebreak()";
    }
    if (kind === "raw" && block instanceof RawBlock) {
      // The raw content is opaque to Typcast, so it is emitted as it is.
      return block.value;
    }
    throwEmit(
      CODE_EMIT_UNKNOWN_TYPE,
      `'${path}/type' is not a known block type.`,
      `${path}/type`,
      { type: kind },
    );
  }

  /** Returns the source of a list block. */
  private list(block: ListBlock, path: string): string {
    const marker = block.ordered ? "+ " : "- ";
    const lines: string[] = [];
    block.items.forEach((item, index) => {
      lines.push(marker + this.inline(item, `${path}/items/${index}`));
    });
    return lines.join("\n");
  }

  /** Returns the source of a table block. */
  private table(block: Table, path: string): string {
    const columns = block.columns.length;
    const align = block.columns.map((column) => column.align).join(", ");
    const lines: string[] = [
      "#table(",
      `  columns: ${columns},`,
      `  align: (${align}),`,
    ];
    const header = block.columns
      .map(
        (column, index) =>
          `[${this.cell(column.header, `${path}/columns/${index}/header`)}]`,
      )
      .join(", ");
    lines.push(`  table.header(${header}),`);
    block.rows.forEach((row, rowIndex) => {
      const cells = row
        .map(
          (cell, cellIndex) =>
            `[${this.cell(cell, `${path}/rows/${rowIndex}/${cellIndex}`)}]`,
        )
        .join(", ");
      lines.push(`  ${cells},`);
    });
    lines.push(")");
    return lines.join("\n");
  }

  /** Returns the content of one cell of a table. */
  private cell(spans: readonly Span[], path: string): string {
    return this.inline(spans, path, true);
  }

  /** Returns the source of an image block. */
  private image(block: Image, path: string): string {
    const arguments_: string[] = [
      `"${escapeString(normalizePath(block.path))}",` +
        ` alt: "${escapeString(block.alt)}"`,
    ];
    if (block.width !== null) {
      arguments_.push(`width: ${formatLength(block.width)}`);
    }
    const image = `image(${arguments_.join(", ")})`;
    const lines: string[] = ["#figure(", `  ${image},`];
    if (block.caption !== null) {
      const caption = this.inline(block.caption, `${path}/caption`, true);
      lines.push(`  caption: [${caption}],`);
    }
    lines.push(")");
    return lines.join("\n");
  }

  // -------------------------------------------------------------------------
  // The inline spans of the output
  // -------------------------------------------------------------------------

  /** Returns the source of a collection of inline spans. */
  private inline(
    spans: readonly Span[],
    path: string,
    lineStart = false,
  ): string {
    let text = "";
    spans.forEach((span, index) => {
      text += this.span(span, `${path}/${index}`, lineStart && index === 0);
    });
    return text;
  }

  /** Returns the source of one inline span. */
  private span(span: Span, path: string, lineStart: boolean): string {
    const kind = span.type;
    if (kind === "text" && span instanceof Text) {
      return escapeText(span.value, lineStart);
    }
    if (kind === "bold" && span instanceof Bold) {
      return `*${this.inline(span.content, `${path}/content`)}*`;
    }
    if (kind === "italic" && span instanceof Italic) {
      return `_${this.inline(span.content, `${path}/content`)}_`;
    }
    if (kind === "monospace" && span instanceof Monospace) {
      return `\`${this.rawText(span.content, `${path}/content`)}\``;
    }
    if (kind === "link" && span instanceof Link) {
      const href = escapeString(span.href);
      const content = this.inline(span.content, `${path}/content`, true);
      return `#link("${href}")[${content}]`;
    }
    if (kind === "lineBreak" && span instanceof LineBreak) {
      return "#linebreak()";
    }
    if (kind === "raw" && span instanceof RawSpan) {
      // The raw content is opaque to Typcast, so it is emitted as it is.
      return span.value;
    }
    throwEmit(
      CODE_EMIT_UNKNOWN_TYPE,
      `'${path}/type' is not a known span type.`,
      `${path}/type`,
      { type: kind },
    );
  }

  /**
   * Returns the content of a monospace span as raw text.
   *
   * The raw text of Typst holds no escape sequence, so the content of a
   * monospace span is emitted as it is. A span of another type and a backtick
   * cannot be represented in the raw text, so the emitter reports them with
   * `TYPCAST-EMIT-0003`.
   */
  private rawText(spans: readonly Span[], path: string): string {
    let text = "";
    spans.forEach((span, index) => {
      const location = `${path}/${index}`;
      if (span instanceof Text) {
        text += this.rawTextValue(span.value, `${location}/value`);
        return;
      }
      if (span instanceof RawSpan) {
        text += this.rawTextValue(span.value, `${location}/value`);
        return;
      }
      throwEmit(
        CODE_EMIT_UNSAFE_VALUE,
        `'${location}/type' is a span of the type '${span.type}', ` +
          "which the raw text of Typst cannot hold.",
        `${location}/type`,
        { expected: "text or raw content", type: span.type },
      );
    });
    return text;
  }

  /** Returns a value of the raw text of Typst. */
  private rawTextValue(value: string, path: string): string {
    if (value.includes("`")) {
      throwEmit(
        CODE_EMIT_UNSAFE_VALUE,
        `'${path}' holds a backtick, which the raw text of Typst cannot hold.`,
        path,
        { expected: "text without a backtick" },
      );
    }
    return value;
  }
}
