/**
 * Unit tests for the Typst emitter.
 *
 * The tests cover the emitter of the TypeScript SDK: the shape of the output,
 * the escaping rules, the raw text of a monospace span, and the diagnostics
 * that the emitter reports.
 */

import {
  ApiUsageError,
  Bold,
  Document,
  EmitError,
  Heading,
  Image,
  Italic,
  Length,
  Link,
  ListBlock,
  Margin,
  Metadata,
  Module,
  Monospace,
  Page,
  Paragraph,
  RawBlock,
  RawSpan,
  Table,
  TableColumn,
  Text,
  ValidationError,
} from "../lib/src/index.js";
import { BlockBase } from "../lib/src/models/blocks.js";
import type { Block, Diagnostic, TypcastOptions } from "../lib/src/index.js";

const failures: string[] = [];

function check(condition: boolean, message: string): void {
  if (!condition) {
    failures.push(message);
  }
}

function checkEqual(actual: unknown, expected: unknown, message: string): void {
  if (actual !== expected) {
    failures.push(`${message}: expected ${String(expected)}, got ${String(actual)}`);
  }
}

function checkIncludes(source: string, expected: string, message: string): void {
  if (!source.includes(expected)) {
    failures.push(`${message}: the source must hold ${JSON.stringify(expected)}`);
  }
}

/** Returns the page of the test documents. */
function page(): Page {
  return new Page(
    "a4",
    "portrait",
    new Margin(
      Length.cm(2.0),
      Length.cm(2.0),
      Length.cm(2.0),
      Length.cm(2.0),
    ),
  );
}

/** Returns a document that the model accepts. */
function document(
  contents: readonly Block[] = [new Paragraph([new Text("Body")])],
  modules: readonly Module[] = [],
): Document {
  return new Document(new Metadata("Title"), page(), contents, modules);
}

/** Returns the error that a call raises, or undefined when it raises none. */
function raised(factory: () => unknown): unknown {
  try {
    factory();
  } catch (error) {
    return error;
  }
  return undefined;
}

/**
 * A block whose type the emitter does not know.
 *
 * The model accepts every block that is a `BlockBase`, and the emitter
 * dispatches on the `type` discriminator, so a block of an unknown type
 * reaches the emitter.
 */
class UnknownBlock extends BlockBase {
  readonly type: "unknown" = "unknown";

  toJSON(): Record<string, unknown> {
    return { type: this.type };
  }
}

function outputTests(): void {
  const source = document().toTypst();
  check(
    source.startsWith("// Generated by Typcast. Do not edit.\n"),
    "the output must start with the header of the contract",
  );
  check(source.endsWith("\n"), "the output ends with a newline");
  check(!source.endsWith("\n\n"), "the output ends with exactly one newline");
  checkIncludes(
    source,
    "\n\n#set page(\n",
    "the page setup follows the header with one blank line",
  );
  checkIncludes(
    source,
    "#set page(\n" +
      '  paper: "a4",\n' +
      "  flipped: false,\n" +
      "  margin: (top: 2cm, right: 2cm, bottom: 2cm, left: 2cm),\n" +
      ")",
    "the page setup must follow the page of the document",
  );
  checkIncludes(
    source,
    "#set document(\n  title: \"Title\",\n)",
    "the metadata of a document without an author and a date holds the title only",
  );
}

function landscapeTests(): void {
  const value = new Document(
    new Metadata("Title"),
    new Page("a4", "landscape", page().margin),
    [new Paragraph([new Text("Body")])],
  );
  checkIncludes(value.toTypst(), "  flipped: true,\n", "a landscape page is flipped");
}

function metadataTests(): void {
  const value = new Document(
    new Metadata("Title", "Author", "2026-11-28"),
    page(),
    [new Paragraph([new Text("Body")])],
  );
  checkIncludes(
    value.toTypst(),
    "#set document(\n" +
      '  title: "Title",\n' +
      '  author: "Author",\n' +
      "  date: datetime(year: 2026, month: 11, day: 28),\n" +
      ")",
    "the metadata must hold the author and the date",
  );
}

function escapingTests(): void {
  const characters = "\\#*_`$[]<>@";
  const expected = Array.from(characters, (character) => `\\${character}`).join("");
  const value = document([new Paragraph([new Text(characters)])]);
  checkIncludes(
    value.toTypst(),
    `${expected}\n`,
    "a text must escape the characters of the table",
  );
}

function listMarkerTests(): void {
  checkIncludes(
    document([new Paragraph([new Text("- A bullet")])]).toTypst(),
    "\\- A bullet\n",
    "a text that starts a line must escape a list marker",
  );
  checkIncludes(
    document([new Paragraph([new Text("+ A number")])]).toTypst(),
    "\\+ A number\n",
    "a text that starts a line must escape a number marker",
  );
  checkIncludes(
    document([new Paragraph([new Text("A - bullet")])]).toTypst(),
    "A - bullet\n",
    "a text that does not start a line must keep a list marker",
  );
  checkIncludes(
    document([new Paragraph([new Text("-dash")])]).toTypst(),
    "-dash\n",
    "a list marker without a space must not be escaped",
  );
  const lists = document([
    new ListBlock(false, [[new Text("First")]]),
    new ListBlock(true, [[new Text("Second")]]),
  ]);
  const source = lists.toTypst();
  checkIncludes(source, "- First\n", "an unordered item holds the hyphen");
  checkIncludes(source, "+ Second\n", "an ordered item holds the plus");
}

function blockTests(): void {
  checkIncludes(
    document([new Heading(3, [new Text("Heading")])]).toTypst(),
    "=== Heading\n",
    "a heading must hold the markers of its level",
  );

  const table = document([
    new Table(
      [
        new TableColumn([new Text("Metric")], "left"),
        new TableColumn([new Text("Value")], "right"),
      ],
      [[[new Text("Revenue")], [new Text("1200")]]],
    ),
  ]);
  checkIncludes(
    table.toTypst(),
    "#table(\n" +
      "  columns: 2,\n" +
      "  align: (left, right),\n" +
      "  table.header([Metric], [Value]),\n" +
      "  [Revenue], [1200],\n" +
      ")",
    "a table must hold its columns and its rows",
  );

  const image = document([new Image("figures/a.png", "A figure")]);
  checkIncludes(
    image.toTypst(),
    '#figure(\n  image("figures/a.png", alt: "A figure"),\n)',
    "an image must hold its path and its alternative text",
  );

  const paths = document(
    [new Image("figures\\a.png", "A figure")],
    [new Module("modules\\report.typ", "report")],
  );
  const pathSource = paths.toTypst();
  checkIncludes(
    pathSource,
    'image("figures/a.png", alt: "A figure")',
    "an image path must use the separator of Typst",
  );
  checkIncludes(
    pathSource,
    '#import "modules/report.typ" as report',
    "a module path must use the separator of Typst",
  );

  const nested = document([
    new Paragraph([new Italic([new Bold([new Text("nested")])])]),
  ]);
  checkIncludes(
    nested.toTypst(),
    "_*nested*_\n",
    "a nested emphasis must be emitted recursively",
  );

  const raw = document([new RawBlock("markup", "#let x = 1")]);
  checkIncludes(raw.toTypst(), "#let x = 1\n", "a raw value is emitted verbatim");

  const rawSpan = document([new Paragraph([new RawSpan("markup", "#x")])]);
  checkIncludes(rawSpan.toTypst(), "#x\n", "a raw span is emitted verbatim");

  const link = document([
    new Paragraph([new Link("https://example.com", [new Text("Site")])]),
  ]);
  checkIncludes(
    link.toTypst(),
    '#link("https://example.com")[Site]\n',
    "a link must hold its target and its content",
  );
}

function moduleTests(): void {
  const body = [new Paragraph([new Text("Body")])];
  checkIncludes(
    document(body, [new Module("modules/report.typ", "report")]).toTypst(),
    '#import "modules/report.typ" as report\n',
    "a module with an alias must be imported as it is",
  );
  checkIncludes(
    document(body, [new Module("modules/format.typ", null, ["currency", "percent"])])
      .toTypst(),
    '#import "modules/format.typ": currency, percent\n',
    "a module with items must be imported with its items",
  );
}

function monospaceTests(): void {
  const value = document([new Paragraph([new Monospace([new Text("a*b")])])]);
  checkIncludes(value.toTypst(), "`a*b`\n", "a monospace span must be raw text");

  const backtick = raised(() =>
    document([new Paragraph([new Monospace([new Text("a`b")])])]).toTypst(),
  );
  check(backtick instanceof EmitError, "a backtick in a monospace span is reported");
  if (backtick instanceof EmitError) {
    const diagnostic = backtick.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-EMIT-0003", "the code must match");
    checkEqual(diagnostic.phase, "emit", "the phase must match");
  }

  const nested = raised(() =>
    document([
      new Paragraph([new Monospace([new Bold([new Text("a")])])]),
    ]).toTypst(),
  );
  check(
    nested instanceof EmitError,
    "a span of another type in a monospace span is reported",
  );
  if (nested instanceof EmitError) {
    const diagnostic = nested.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-EMIT-0003", "the code must match");
  }
}

function validationTests(): void {
  const broken = document([
    new Table(
      [new TableColumn([new Text("Metric")], "left")],
      [[[new Text("Revenue")], [new Text("1200")]]],
    ),
  ]);
  const error = raised(() => broken.toTypst());
  check(error instanceof ValidationError, "a broken document must be reported");
  if (error instanceof ValidationError) {
    const diagnostic = error.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-VAL-0007", "the code must match");
  }
}

function unknownTypeTests(): void {
  const value = document([new UnknownBlock() as unknown as Block]);
  const error = raised(() => value.toTypst());
  check(error instanceof EmitError, "an unknown block type must be reported");
  if (error instanceof EmitError) {
    const diagnostic = error.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-EMIT-0002", "the code must match");
    checkEqual(diagnostic.phase, "emit", "the phase must match");
    checkEqual(diagnostic.path, "/contents/0/type", "the path must match");
  }
}

function configurationTests(): void {
  const error = raised(() =>
    document().toTypst("not an options object" as unknown as TypcastOptions),
  );
  check(error instanceof ApiUsageError, "a wrong options object is reported");
  if (error instanceof ApiUsageError) {
    const diagnostic = error.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-API-0001", "the code must match");
    checkEqual(diagnostic.path, "/to_typst", "the path must match");
  }

  const raw = document([new RawBlock("markup", "0123456789")]);
  checkIncludes(
    raw.toTypst({ maxRawBytes: 10 }),
    "0123456789\n",
    "a raw node at the limit of the configuration must be accepted",
  );
  const over = raised(() => raw.toTypst({ maxRawBytes: 9 }));
  check(over instanceof ValidationError, "a raw node over the limit is reported");
  if (over instanceof ValidationError) {
    const diagnostic = over.diagnostics[0] as Diagnostic;
    checkEqual(diagnostic.code, "TYPCAST-VAL-0010", "the code must match");
  }
}

outputTests();
landscapeTests();
metadataTests();
escapingTests();
listMarkerTests();
blockTests();
moduleTests();
monospaceTests();
validationTests();
unknownTypeTests();
configurationTests();

if (failures.length > 0) {
  for (const failure of failures) {
    console.error(`ERROR ${failure}`);
  }
  console.error(`failures: ${failures.length}`);
  throw new Error(`${failures.length} unit test failures`);
}
console.log("failures: 0");
