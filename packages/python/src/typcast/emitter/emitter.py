"""The Typst emitter of the document IR.

The emitter turns a validated document into deterministic Typst source. It is a
pure function of the document: it reads no file, invokes no compiler, and
writes no file. The TypeScript SDK applies the same rules in
`src/emitter/emitter.ts`, so that both SDKs produce the same bytes for the
same document.

The output contract is the one of `docs/specifications/emitter.md`, and the
escaping rules are the ones of `docs/specifications/nodes.md`.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Sequence

from typcast.diagnostics import (
    CODE_EMIT_INVARIANT,
    CODE_EMIT_UNKNOWN_TYPE,
    CODE_EMIT_UNSAFE_VALUE,
    raise_emit,
)
from typcast.models.blocks import (
    Block,
    Heading,
    Image,
    ListBlock,
    PageBreak,
    Paragraph,
    RawBlock,
    Table,
)
from typcast.models.document import Document
from typcast.models.module import Module
from typcast.models.page import Length
from typcast.models.spans import (
    Bold,
    Italic,
    LineBreak,
    Link,
    Monospace,
    RawSpan,
    Span,
    Text,
)
from typcast.numbers import format_number

if TYPE_CHECKING:
    from typcast.validations.config import TypcastConfig

__all__ = [
    "EMITTER_HEADER",
    "emit_typst",
    "escape_string",
    "escape_text",
    "format_length",
    "normalize_path",
]

# The header of every generated file. It names no version, so that a release
# does not change the golden files.
EMITTER_HEADER = "// Generated by Typcast. Do not edit."

# The characters that a text span escapes in the markup of Typst. The rule is
# the one of the escaping table of `docs/specifications/nodes.md`. The
# TypeScript SDK applies the same rule.
_TEXT_ESCAPES = {
    "\\": "\\\\",
    "#": "\\#",
    "*": "\\*",
    "_": "\\_",
    "`": "\\`",
    "$": "\\$",
    "[": "\\[",
    "]": "\\]",
    "<": "\\<",
    ">": "\\>",
    "@": "\\@",
}

# The characters that a string literal escapes. A string literal of Typst
# holds no markup, so only the backslash and the quote need an escape. The
# TypeScript SDK applies the same rule.
_STRING_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
}

# The list markers of the markup of Typst. A text that starts a line and
# starts with a marker would open a list, so the marker is escaped.
_LIST_MARKERS = ("-", "+")

# The pattern of a date of the metadata. The model checks the pattern already,
# so a value that does not match it means that an invariant of the model broke.
_DATE_PATTERN = re.compile(r"([0-9]{4})-([0-9]{2})-([0-9]{2})")

# The sides of a margin, in the order of the emission.
_MARGIN_SIDES = ("top", "right", "bottom", "left")


def escape_text(value: str, *, line_start: bool = False) -> str:
    """Returns the text of a span in the markup of Typst.

    Every character of the escaping table of the node catalog is escaped. A
    text that starts a line and starts with a list marker is escaped as well,
    because Typst would read the marker as the start of a list. The
    TypeScript SDK applies the same rule.
    """
    text = "".join(_TEXT_ESCAPES.get(character, character) for character in value)
    if line_start and value[:1] in _LIST_MARKERS and (
        len(value) == 1 or value[1] == " "
    ):
        text = "\\" + text
    return text


def escape_string(value: str) -> str:
    """Returns the value in a string literal of Typst.

    A string literal holds no markup, so only the backslash and the quote are
    escaped. The TypeScript SDK applies the same rule.
    """
    return "".join(_STRING_ESCAPES.get(character, character) for character in value)


def normalize_path(value: str) -> str:
    """Returns the path of an asset with the separator of Typst.

    The path of the IR uses the separator `/`, and the emitter emits it with
    that separator. A path that holds a backslash is normalized, so that the
    same asset is named on every platform.
    """
    return value.replace("\\", "/")


def format_length(length: Length) -> str:
    """Returns the length in the form of Typst.

    The number is written in the canonical form of the IR, so that both SDKs
    write the same text, and the unit follows the number without a space.
    """
    return f"{format_number(length.value)}{length.unit}"


def emit_typst(document: Document, config: "TypcastConfig | None" = None) -> str:
    """Returns the Typst source of a document.

    The function validates the document before it emits it, so that a document
    that breaks a semantic rule is reported with the diagnostic of the rule
    instead of being emitted. The configuration holds the limits of the
    validation run, and it is never stored in the document.
    """
    from typcast.api import require_api_instance
    from typcast.diagnostics import SEVERITY_ERROR, ValidationError
    from typcast.validations.config import TypcastConfig

    settings = (
        TypcastConfig()
        if config is None
        else require_api_instance(
            config,
            TypcastConfig,
            "/to_typst",
            "TypcastConfig",
        )
    )
    diagnostics = document.validate(settings)
    errors = tuple(
        diagnostic
        for diagnostic in diagnostics
        if diagnostic.severity == SEVERITY_ERROR
    )
    if errors:
        raise ValidationError(errors[0].message, errors)
    return _Emitter(document).emit()


class _Emitter:
    """Turns a document into Typst source.

    The class holds the state of one emission. Every method returns a part of
    the output, and `emit()` joins the parts with the blank lines of the
    output contract.
    """

    def __init__(self, document: Document) -> None:
        self._document = document

    def emit(self) -> str:
        """Returns the Typst source of the document."""
        sections = [EMITTER_HEADER]
        imports = self._imports()
        if imports:
            sections.append(imports)
        sections.append(self._page_setup())
        sections.append(self._metadata())
        for index, block in enumerate(self._document.contents):
            sections.append(self._block(block, f"/contents/{index}"))
        # The output ends with exactly one newline.
        return "\n\n".join(sections) + "\n"

    # -- The sections of the output -----------------------------------------

    def _imports(self) -> str:
        """Returns the import section of the output."""
        lines = []
        for index, module in enumerate(self._document.modules):
            lines.append(self._import(module, f"/modules/{index}"))
        return "\n".join(lines)

    def _import(self, module: Module, path: str) -> str:
        """Returns the import of one module."""
        source = escape_string(normalize_path(module.path))
        if module.alias is not None:
            return f'#import "{source}" as {module.alias}'
        items = module.items if module.items is not None else ()
        return f'#import "{source}": {", ".join(items)}'

    def _page_setup(self) -> str:
        """Returns the page setup of the output."""
        page = self._document.page
        margin = page.margin
        sides = ", ".join(
            f"{side}: {format_length(getattr(margin, side))}"
            for side in _MARGIN_SIDES
        )
        flipped = "true" if page.orientation == "landscape" else "false"
        return "\n".join(
            [
                "#set page(",
                f'  paper: "{escape_string(page.paper)}",',
                f"  flipped: {flipped},",
                f"  margin: ({sides}),",
                ")",
            ]
        )

    def _metadata(self) -> str:
        """Returns the document metadata of the output."""
        metadata = self._document.metadata
        lines = [
            "#set document(",
            f'  title: "{escape_string(metadata.title)}",',
        ]
        if metadata.author is not None:
            lines.append(f'  author: "{escape_string(metadata.author)}",')
        if metadata.date is not None:
            lines.append(f"  date: {self._date(metadata.date, '/metadata/date')},")
        lines.append(")")
        return "\n".join(lines)

    def _date(self, value: str, path: str) -> str:
        """Returns the date of the metadata in the form of Typst."""
        match = _DATE_PATTERN.fullmatch(value)
        if match is None:
            # The model checks the date, so a value that does not match the
            # pattern means that an invariant of the model broke.
            raise_emit(
                CODE_EMIT_INVARIANT,
                f"'{path}' is not a date of the form YYYY-MM-DD.",
                path,
                {"value": value},
            )
        year, month, day = match.groups()
        return f"datetime(year: {year}, month: {month}, day: {day})"

    # -- The blocks of the output -------------------------------------------

    def _block(self, block: Block, path: str) -> str:
        """Returns the source of one block."""
        kind = block.type
        if kind == "heading" and isinstance(block, Heading):
            return "=" * block.level + " " + self._inline(
                block.content,
                f"{path}/content",
            )
        if kind == "paragraph" and isinstance(block, Paragraph):
            return self._inline(block.content, f"{path}/content", line_start=True)
        if kind == "list" and isinstance(block, ListBlock):
            return self._list(block, path)
        if kind == "table" and isinstance(block, Table):
            return self._table(block, path)
        if kind == "image" and isinstance(block, Image):
            return self._image(block, path)
        if kind == "pageBreak" and isinstance(block, PageBreak):
            return "#pagebreak()"
        if kind == "raw" and isinstance(block, RawBlock):
            # The raw content is opaque to Typcast, so it is emitted as it is.
            return block.value
        raise_emit(
            CODE_EMIT_UNKNOWN_TYPE,
            f"'{path}/type' is not a known block type.",
            f"{path}/type",
            {"type": kind},
        )

    def _list(self, block: ListBlock, path: str) -> str:
        """Returns the source of a list block."""
        marker = "+ " if block.ordered else "- "
        lines = []
        for index, item in enumerate(block.items):
            lines.append(marker + self._inline(item, f"{path}/items/{index}"))
        return "\n".join(lines)

    def _table(self, block: Table, path: str) -> str:
        """Returns the source of a table block."""
        columns = len(block.columns)
        align = ", ".join(column.align for column in block.columns)
        lines = [
            "#table(",
            f"  columns: {columns},",
            f"  align: ({align}),",
        ]
        header = ", ".join(
            f"[{self._cell(column.header, f'{path}/columns/{index}/header')}]"
            for index, column in enumerate(block.columns)
        )
        lines.append(f"  table.header({header}),")
        for row_index, row in enumerate(block.rows):
            cells = ", ".join(
                f"[{self._cell(cell, f'{path}/rows/{row_index}/{cell_index}')}]"
                for cell_index, cell in enumerate(row)
            )
            lines.append(f"  {cells},")
        lines.append(")")
        return "\n".join(lines)

    def _cell(self, spans: Sequence[Span], path: str) -> str:
        """Returns the content of one cell of a table."""
        return self._inline(spans, path, line_start=True)

    def _image(self, block: Image, path: str) -> str:
        """Returns the source of an image block."""
        arguments = [
            f'"{escape_string(normalize_path(block.path))}",'
            f' alt: "{escape_string(block.alt)}"'
        ]
        if block.width is not None:
            arguments.append(f"width: {format_length(block.width)}")
        image = f"image({', '.join(arguments)})"
        lines = [
            "#figure(",
            f"  {image},",
        ]
        if block.caption is not None:
            caption = self._inline(block.caption, f"{path}/caption", line_start=True)
            lines.append(f"  caption: [{caption}],")
        lines.append(")")
        return "\n".join(lines)

    # -- The inline spans of the output -------------------------------------

    def _inline(
        self,
        spans: Sequence[Span],
        path: str,
        *,
        line_start: bool = False,
    ) -> str:
        """Returns the source of a collection of inline spans."""
        parts = []
        for index, span in enumerate(spans):
            parts.append(
                self._span(
                    span,
                    f"{path}/{index}",
                    line_start=line_start and index == 0,
                )
            )
        return "".join(parts)

    def _span(self, span: Span, path: str, *, line_start: bool) -> str:
        """Returns the source of one inline span."""
        kind = span.type
        if kind == "text" and isinstance(span, Text):
            return escape_text(span.value, line_start=line_start)
        if kind == "bold" and isinstance(span, Bold):
            return "*" + self._inline(span.content, f"{path}/content") + "*"
        if kind == "italic" and isinstance(span, Italic):
            return "_" + self._inline(span.content, f"{path}/content") + "_"
        if kind == "monospace" and isinstance(span, Monospace):
            return "`" + self._raw_text(span.content, f"{path}/content") + "`"
        if kind == "link" and isinstance(span, Link):
            href = escape_string(span.href)
            content = self._inline(span.content, f"{path}/content", line_start=True)
            return f'#link("{href}")[{content}]'
        if kind == "lineBreak" and isinstance(span, LineBreak):
            return "#linebreak()"
        if kind == "raw" and isinstance(span, RawSpan):
            # The raw content is opaque to Typcast, so it is emitted as it is.
            return span.value
        raise_emit(
            CODE_EMIT_UNKNOWN_TYPE,
            f"'{path}/type' is not a known span type.",
            f"{path}/type",
            {"type": kind},
        )

    def _raw_text(self, spans: Sequence[Span], path: str) -> str:
        """Returns the content of a monospace span as raw text.

        The raw text of Typst holds no escape sequence, so the content of a
        monospace span is emitted as it is. A span of another type and a
        backtick cannot be represented in the raw text, so the emitter reports
        them with `TYPCAST-EMIT-0003`.
        """
        parts = []
        for index, span in enumerate(spans):
            location = f"{path}/{index}"
            if isinstance(span, Text):
                parts.append(self._raw_text_value(span.value, f"{location}/value"))
                continue
            if isinstance(span, RawSpan):
                parts.append(self._raw_text_value(span.value, f"{location}/value"))
                continue
            raise_emit(
                CODE_EMIT_UNSAFE_VALUE,
                f"'{location}/type' is a span of the type '{span.type}', "
                "which the raw text of Typst cannot hold.",
                f"{location}/type",
                {"expected": "text or raw content", "type": span.type},
            )
        return "".join(parts)

    def _raw_text_value(self, value: str, path: str) -> str:
        """Returns a value of the raw text of Typst."""
        if "`" in value:
            raise_emit(
                CODE_EMIT_UNSAFE_VALUE,
                f"'{path}' holds a backtick, which the raw text of Typst "
                "cannot hold.",
                path,
                {"expected": "text without a backtick"},
            )
        return value
