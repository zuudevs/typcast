"""Unit tests for the Typst emitter.

The tests cover the emitter of the Python SDK: the shape of the output, the
escaping rules, the raw text of a monospace span, and the diagnostics that the
emitter reports.

Usage:

    bazel test //packages/python/tests:emitter_tests
"""

from __future__ import annotations

import unittest
from dataclasses import dataclass
from typing import Any, ClassVar

import typcast
from typcast import (
    CODE_EMIT_UNSAFE_VALUE,
    CODE_EMIT_UNKNOWN_TYPE,
    ApiUsageError,
    Block,
    Bold,
    Document,
    EmitError,
    Heading,
    Image,
    Italic,
    Length,
    Link,
    Margin,
    Metadata,
    Module,
    Monospace,
    Page,
    Paragraph,
    RawBlock,
    RawSpan,
    Table,
    TableColumn,
    Text,
    TypcastConfig,
    ValidationError,
)


def page() -> Page:
    """Returns the page of the test documents."""
    return Page(
        paper="a4",
        orientation="portrait",
        margin=Margin(
            top=Length(2, "cm"),
            right=Length(2, "cm"),
            bottom=Length(2, "cm"),
            left=Length(2, "cm"),
        ),
    )


def document(contents: Any = None, modules: Any = None) -> Document:
    """Returns a document that the model accepts."""
    return Document(
        metadata=Metadata(title="Title"),
        page=page(),
        contents=[Paragraph((Text("Body"),))] if contents is None else contents,
        modules=() if modules is None else modules,
    )


@dataclass(frozen=True)
class UnknownBlock(Block):
    """A block whose type the emitter does not know."""

    type: ClassVar[str] = "unknown"

    def to_dict(self) -> dict[str, Any]:
        return {"type": self.type}


class EmitterTests(unittest.TestCase):
    """Checks the output of the emitter."""

    def test_the_output_starts_with_the_header(self) -> None:
        source = document().to_typst()
        self.assertTrue(
            source.startswith("// Generated by Typcast. Do not edit.\n"),
            "the output must start with the header of the contract",
        )

    def test_the_output_ends_with_exactly_one_newline(self) -> None:
        source = document().to_typst()
        self.assertTrue(source.endswith("\n"), "the output ends with a newline")
        self.assertFalse(
            source.endswith("\n\n"),
            "the output ends with exactly one newline",
        )

    def test_the_sections_are_separated_by_one_blank_line(self) -> None:
        source = document().to_typst()
        self.assertIn(
            "\n\n#set page(\n",
            source,
            "the page setup follows the header with one blank line",
        )

    def test_the_page_setup_follows_the_page_of_the_document(self) -> None:
        source = document().to_typst()
        self.assertIn(
            "#set page(\n"
            '  paper: "a4",\n'
            "  flipped: false,\n"
            "  margin: (top: 2cm, right: 2cm, bottom: 2cm, left: 2cm),\n"
            ")",
            source,
        )

    def test_a_landscape_page_is_flipped(self) -> None:
        value = Page(
            paper="a4",
            orientation="landscape",
            margin=page().margin,
        )
        source = Document(
            metadata=Metadata(title="Title"),
            page=value,
            contents=[Paragraph((Text("Body"),))],
        ).to_typst()
        self.assertIn("  flipped: true,\n", source)

    def test_the_metadata_holds_the_author_and_the_date_only_when_they_are_present(
        self,
    ) -> None:
        source = document().to_typst()
        self.assertIn(
            "#set document(\n  title: \"Title\",\n)",
            source,
            "the metadata of a document without an author and a date holds "
            "the title only",
        )

    def test_the_metadata_holds_the_author_and_the_date(self) -> None:
        value = Document(
            metadata=Metadata(title="Title", author="Author", date="2026-11-28"),
            page=page(),
            contents=[Paragraph((Text("Body"),))],
        )
        source = value.to_typst()
        self.assertIn(
            "#set document(\n"
            '  title: "Title",\n'
            '  author: "Author",\n'
            "  date: datetime(year: 2026, month: 11, day: 28),\n"
            ")",
            source,
        )

    def test_a_heading_holds_the_markers_of_its_level(self) -> None:
        value = document([Heading(3, (Text("Heading"),))])
        self.assertIn("=== Heading\n", value.to_typst())

    def test_a_text_escapes_the_characters_of_the_table(self) -> None:
        characters = "\\#*_`$[]<>@"
        value = document([Paragraph((Text(characters),))])
        source = value.to_typst()
        expected = "".join("\\" + character for character in characters)
        self.assertIn(expected + "\n", source)

    def test_a_text_that_starts_a_line_escapes_a_list_marker(self) -> None:
        value = document([Paragraph((Text("- A bullet"),))])
        self.assertIn("\\- A bullet\n", value.to_typst())

    def test_a_text_that_starts_a_line_escapes_a_number_marker(self) -> None:
        value = document([Paragraph((Text("+ A number"),))])
        self.assertIn("\\+ A number\n", value.to_typst())

    def test_a_text_that_does_not_start_a_line_keeps_a_list_marker(self) -> None:
        value = document([Paragraph((Text("A - bullet"),))])
        self.assertIn("A - bullet\n", value.to_typst())

    def test_a_list_marker_without_a_space_is_not_escaped(self) -> None:
        value = document([Paragraph((Text("-dash"),))])
        self.assertIn("-dash\n", value.to_typst())

    def test_a_list_item_is_emitted_with_the_marker_of_its_kind(self) -> None:
        value = document(
            [
                typcast.ListBlock(
                    ordered=False,
                    items=((Text("First"),),),
                ),
                typcast.ListBlock(
                    ordered=True,
                    items=((Text("Second"),),),
                ),
            ]
        )
        source = value.to_typst()
        self.assertIn("- First\n", source)
        self.assertIn("+ Second\n", source)

    def test_a_table_holds_its_columns_and_its_rows(self) -> None:
        value = document(
            [
                Table(
                    columns=(
                        TableColumn(header=(Text("Metric"),), align="left"),
                        TableColumn(header=(Text("Value"),), align="right"),
                    ),
                    rows=(((Text("Revenue"),), (Text("1200"),)),),
                )
            ]
        )
        source = value.to_typst()
        self.assertIn(
            "#table(\n"
            "  columns: 2,\n"
            "  align: (left, right),\n"
            "  table.header([Metric], [Value]),\n"
            "  [Revenue], [1200],\n"
            ")",
            source,
        )

    def test_an_image_holds_its_path_and_its_alternative_text(self) -> None:
        value = document([Image(path="figures/a.png", alt="A figure")])
        source = value.to_typst()
        self.assertIn(
            '#figure(\n  image("figures/a.png", alt: "A figure"),\n)',
            source,
        )

    def test_a_path_with_a_backslash_uses_the_separator_of_typst(self) -> None:
        value = document(
            [Image(path="figures\\a.png", alt="A figure")],
            [Module(path="modules\\report.typ", alias="report")],
        )
        source = value.to_typst()
        self.assertIn('image("figures/a.png", alt: "A figure")', source)
        self.assertIn('#import "modules/report.typ" as report', source)

    def test_a_nested_emphasis_is_emitted_recursively(self) -> None:
        value = document(
            [Paragraph((Italic(content=(Bold(content=(Text("nested"),)),)),))]
        )
        self.assertIn("_*nested*_\n", value.to_typst())

    def test_a_module_with_an_alias_is_imported_as_it_is(self) -> None:
        value = document(modules=[Module(path="modules/report.typ", alias="report")])
        self.assertIn(
            '#import "modules/report.typ" as report\n',
            value.to_typst(),
        )

    def test_a_module_with_items_is_imported_with_its_items(self) -> None:
        value = document(
            modules=[Module(path="modules/format.typ", items=("currency", "percent"))]
        )
        self.assertIn(
            '#import "modules/format.typ": currency, percent\n',
            value.to_typst(),
        )

    def test_a_raw_value_is_emitted_verbatim(self) -> None:
        value = document([RawBlock(format="markup", value="#let x = 1")])
        self.assertIn("#let x = 1\n", value.to_typst())

    def test_a_raw_span_is_emitted_verbatim(self) -> None:
        value = document([Paragraph((RawSpan(format="markup", value="#x"),))])
        self.assertIn("#x\n", value.to_typst())

    def test_a_link_holds_its_target_and_its_content(self) -> None:
        value = document(
            [Paragraph((Link(href="https://example.com", content=(Text("Site"),)),))]
        )
        self.assertIn(
            '#link("https://example.com")[Site]\n',
            value.to_typst(),
        )

    def test_a_monospace_span_is_raw_text(self) -> None:
        value = document([Paragraph((Monospace(content=(Text("a*b"),)),))])
        self.assertIn("`a*b`\n", value.to_typst())

    def test_a_monospace_span_that_holds_a_backtick_is_reported(self) -> None:
        value = document([Paragraph((Monospace(content=(Text("a`b"),)),))])
        with self.assertRaises(EmitError) as caught:
            value.to_typst()
        self.assertEqual(
            caught.exception.diagnostics[0].code,
            CODE_EMIT_UNSAFE_VALUE,
        )
        self.assertEqual(caught.exception.diagnostics[0].phase, "emit")

    def test_a_monospace_span_that_holds_another_span_is_reported(self) -> None:
        value = document(
            [Paragraph((Monospace(content=(Bold(content=(Text("a"),)),)),))]
        )
        with self.assertRaises(EmitError) as caught:
            value.to_typst()
        self.assertEqual(
            caught.exception.diagnostics[0].code,
            CODE_EMIT_UNSAFE_VALUE,
        )

    def test_an_unknown_block_type_is_reported(self) -> None:
        value = document([UnknownBlock()])
        with self.assertRaises(EmitError) as caught:
            value.to_typst()
        self.assertEqual(
            caught.exception.diagnostics[0].code,
            CODE_EMIT_UNKNOWN_TYPE,
        )

    def test_a_document_that_breaks_a_semantic_rule_is_reported(self) -> None:
        value = document(
            [
                Table(
                    columns=(TableColumn(header=(Text("Metric"),), align="left"),),
                    rows=(((Text("Revenue"),), (Text("1200"),)),),
                )
            ]
        )
        with self.assertRaises(ValidationError) as caught:
            value.to_typst()
        self.assertEqual(caught.exception.diagnostics[0].code, "TYPCAST-VAL-0007")

    def test_a_configuration_of_the_wrong_type_is_reported(self) -> None:
        with self.assertRaises(ApiUsageError) as caught:
            document().to_typst(config="not a configuration")
        self.assertEqual(caught.exception.diagnostics[0].code, "TYPCAST-API-0001")
        self.assertEqual(caught.exception.diagnostics[0].path, "/to_typst")

    def test_a_raw_limit_of_the_configuration_holds_the_raw_nodes(self) -> None:
        value = document([RawBlock(format="markup", value="0123456789")])
        self.assertIn("0123456789\n", value.to_typst(TypcastConfig(max_raw_bytes=10)))
        with self.assertRaises(ValidationError) as caught:
            value.to_typst(TypcastConfig(max_raw_bytes=9))
        self.assertEqual(caught.exception.diagnostics[0].code, "TYPCAST-VAL-0010")


if __name__ == "__main__":
    unittest.main()
